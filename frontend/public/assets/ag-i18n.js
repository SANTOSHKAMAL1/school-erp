  var loaded = {};
  function ensureFont(lang) {
    var pair = FONTS[lang];
    if (!pair || loaded[lang]) return;
    loaded[lang] = true;
    var href = 'https://fonts.googleapis.com/css2?family=' +
      pair[0].replace(/ /g, '+') + ':wght@400;600;700&family=' +
      pair[1].replace(/ /g, '+') + ':wght@400;600;700&display=swap';
    var l = document.createElement('link');
    l.rel = 'stylesheet';
    l.href = href;
    document.head.appendChild(l);
  }

  var swapped = null;

  function table(lang) {
    var i = ORDER.indexOf(lang);
    if (i < 0) return null;
    var out = {};
    for (var k in T) {
      var v = T[k][i];
      if (v) {
        out[k] = v;
      }
    }
    return out;
  }

  function restore() {
    if (!swapped) return;
    for (var i = 0; i < swapped.length; i++) swapped[i][0].nodeValue = swapped[i][1];
    swapped = null;
  }

  function apply(lang) {
    if (typeof document === 'undefined' || !document.body) return;
    var root = document.documentElement;
    if (!lang || lang === 'en') {
      root.style.removeProperty('--font-body');
      root.style.removeProperty('--font-heading');
      root.setAttribute('lang', 'en');
      restore();
      decorateLinks('en');
      return;
    }
    var d = table(lang);
    if (!d) return;
    ensureFont(lang);
    var pair = FONTS[lang];
    root.style.setProperty('--font-body', "'" + pair[0] + "','Figtree',sans-serif");
    root.style.setProperty('--font-heading', "'" + pair[1] + "','Caprasimo',serif");
    root.setAttribute('lang', lang);

    restore();
    var pairs = [];
    var walk = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
    var n;
    while ((n = walk.nextNode())) {
      if (n.parentNode && n.parentNode.nodeName === 'OPTION') continue;
      var raw = n.nodeValue;
      var key = raw.trim();
      if (!key || !d[key]) continue;
      pairs.push([n, raw]);
      n.nodeValue = raw.replace(key, d[key]);
    }
    swapped = pairs;
    decorateLinks(lang);
  }

  /* edits only the lang key — every other query parameter survives */
  function withLang(href, lang) {
    var hash = '';
    var h = href.indexOf('#');
    if (h > -1) { hash = href.slice(h); href = href.slice(0, h); }
    var q = href.indexOf('?');
    var base = q > -1 ? href.slice(0, q) : href;
    var search = q > -1 ? href.slice(q + 1) : '';
    var parts = search ? search.split('&') : [];
    var kept = [];
    for (var i = 0; i < parts.length; i++) {
      if (!parts[i] || parts[i].slice(0, 5) === 'lang=') continue;
      kept.push(parts[i]);
    }
    if (lang && lang !== 'en') kept.push('lang=' + lang);
    return base + (kept.length ? '?' + kept.join('&') : '') + hash;
  }

  function decorateLinks(lang) {
    var as = document.querySelectorAll('a[href]');
    for (var i = 0; i < as.length; i++) {
      var raw = as[i].getAttribute('href');
      if (!raw || raw.indexOf('.dc.html') < 0 || /^https?:/i.test(raw)) continue;
      as[i].setAttribute('href', withLang(raw, lang));
    }
  }

  function fromUrl() {
    try {
      var m = (window.location.search || '').match(/[?&]lang=([a-z]{2})/i);
      return m ? m[1].toLowerCase() : '';
    } catch (e) { return ''; }
  }

  function cookieGet() {
    try {
      var m = (document.cookie || '').match(/(?:^|;\s*)ag-lang=([a-z]{2})/i);
      return m ? m[1].toLowerCase() : '';
    } catch (e) { return ''; }
  }

  function cookieSet(v) {
    try { document.cookie = 'ag-lang=' + v + ';path=/;max-age=31536000;samesite=lax'; } catch (e) {}
  }

  /* resolved once, synchronously, at first evaluation — the URL param seeds it,
     a user pick replaces it, and nothing else may override it afterwards */
  if (!window.__AG_I18N_CHOSEN) window.__AG_I18N_CHOSEN = fromUrl() || 'en';

  function current() { return window.__AG_I18N_CHOSEN || 'en'; }

  if (!window.__AG_I18N_SUBS) window.__AG_I18N_SUBS = [];
  var subs = window.__AG_I18N_SUBS;

  function set(lang) {
    var v = lang || 'en';
    window.__AG_I18N_CHOSEN = v;
    /* keep the address bar in step so a reload cannot resurrect the old value */
    try {
      if (window.history && window.history.replaceState) {
        var here = window.location.pathname + (window.location.search || '') + (window.location.hash || '');
        window.history.replaceState(null, '', withLang(here, v));
      }
    } catch (e) {}
    apply(v);
    try { if (window.__AG_I18N_TIMER) clearInterval(window.__AG_I18N_TIMER); } catch (e) {}
    if (v !== 'en') window.__AG_I18N_TIMER = setInterval(AG.reapply, 1200);
    for (var i = 0; i < subs.length; i++) { try { subs[i](v); } catch (e) {} }
  }

  var AG = {
    langs: LANGS,
    apply: apply,
    set: set,
    current: current,
    subscribe: function (fn) { if (typeof fn === 'function') { subs.push(fn); fn(current()); } },
    reapply: function () { var l = current(); if (l && l !== 'en') apply(l); }
  };
  window.AG_I18N = AG;

  function bindClicks() {
    if (window.__AG_I18N_CLICK) return;
    window.__AG_I18N_CLICK = true;
    document.addEventListener('click', function (ev) {
      var lang = current();
      var a = ev.target;
      while (a && a.nodeName !== 'A') a = a.parentNode;
      if (!a || !a.getAttribute) return;
      var raw = a.getAttribute('href');
      if (!raw || raw.indexOf('.dc.html') < 0 || /^https?:/i.test(raw)) return;
      if (raw.indexOf('nav=1') < 0) {
        var mark = raw.indexOf('#') > -1
          ? raw.replace('#', (raw.indexOf('?') > -1 ? '&' : '?') + 'nav=1#')
          : raw + (raw.indexOf('?') > -1 ? '&' : '?') + 'nav=1';
        raw = mark;
        a.setAttribute('href', raw);
      }
      a.setAttribute('href', withLang(raw, lang));
    }, true);
  }

  function boot() {
    var l = current();
    if (l !== 'en') {
      try { localStorage.setItem('ag-lang', l); } catch (e) {}
      cookieSet(l);
      apply(l);
    } else {
      decorateLinks('en');
    }
    bindClicks();
    for (var i = 0; i < subs.length; i++) { try { subs[i](l); } catch (e) {} }
    /* pages re-render (counters, menus, form states) — keep the swap fresh */
    try { if (window.__AG_I18N_TIMER) clearInterval(window.__AG_I18N_TIMER); } catch (e) {}
    if (current() !== 'en') window.__AG_I18N_TIMER = setInterval(AG.reapply, 1200);
    /* keep tabs in step */
    window.addEventListener('storage', function (e) {
      if (e.key !== 'ag-lang' || !e.newValue) return;
      window.__AG_I18N_CHOSEN = e.newValue;
      apply(e.newValue);
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }
  setTimeout(boot, 700);
